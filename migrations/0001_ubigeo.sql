-- Departamentos, provincias y distritos del Perú con su población.
--
-- Fuente: INEI, «Perú: Crecimiento y distribución de la población total, 2017» (Censo 2017).
--   poblacion_censada: población censada el 22 de octubre de 2017.
--   poblacion_total:   población censada más la estimada por omisión censal.
-- El ubigeo es el código oficial de 2, 4 y 6 dígitos (departamento, provincia, distrito).

create table if not exists departamentos (
    ubigeo            char(2) primary key,
    nombre            text    not null,
    poblacion_censada integer not null,
    poblacion_total   integer not null
);

create table if not exists provincias (
    ubigeo              char(4) primary key,
    departamento_ubigeo char(2) not null references departamentos (ubigeo),
    nombre              text    not null,
    poblacion_censada   integer not null,
    poblacion_total     integer not null
);

create table if not exists distritos (
    ubigeo              char(6) primary key,
    provincia_ubigeo    char(4) not null references provincias (ubigeo),
    departamento_ubigeo char(2) not null references departamentos (ubigeo),
    nombre              text    not null,
    poblacion_censada   integer not null,
    poblacion_total     integer not null
);
create index if not exists distritos_provincia on distritos (provincia_ubigeo);
create index if not exists distritos_departamento on distritos (departamento_ubigeo);



